import Foundation

enum ECMType: String, CaseIterable {
    case ddfi1, ddfi2, ddfi3

    static func getType(_ type: String) -> ECMType? {
        switch type {
        case "DDFI": return .ddfi1
        case "DDFI-2": return .ddfi2
        case "DDFI-3": return .ddfi3
        default: return nil
        }
    }

    var displayName: String {
        switch self {
        case .ddfi1: return "DDFI"
        case .ddfi2: return "DDFI-2"
        case .ddfi3: return "DDFI-3"
        }
    }
}

enum ECMProtocol: String, CaseIterable {
    case stock, factoryRace

    var label: String {
        switch self {
        case .stock: return "Stock / P&A"
        case .factoryRace: return "Factory Race"
        }
    }
}

enum DataSource {
    case runtimeData, eeprom
}

enum ECMFunction: Int, CaseIterable {
    case clearCodes = 1
    case frontCoil = 2
    case rearCoil = 3
    case tachometer = 4
    case fuelPump = 5
    case frontInj = 6
    case rearInj = 7
    case tpsReset = 8
    case fan = 9
    case exhValve = 0x0a
    case activeIntake = 0x0b
    case shiftLight = 0x0c

    var displayName: String {
        switch self {
        case .clearCodes: return "Clear Codes"
        case .frontCoil: return "Front Coil"
        case .rearCoil: return "Rear Coil"
        case .tachometer: return "Tachometer"
        case .fuelPump: return "Fuel Pump"
        case .frontInj: return "Front Injector"
        case .rearInj: return "Rear Injector"
        case .tpsReset: return "TPS Reset"
        case .fan: return "Fan"
        case .exhValve: return "Exhaust Valve"
        case .activeIntake: return "Active Intake"
        case .shiftLight: return "Shift Light"
        }
    }
}

